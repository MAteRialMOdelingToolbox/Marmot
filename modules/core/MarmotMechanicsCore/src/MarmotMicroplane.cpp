  Data get( QuadratureScheme scheme )
  {
    const size_t          nqp    = nqpFromScheme( scheme );
    std::vector< double > mpdata = rawQuadratureData( scheme );

    Map< Matrix< double, Eigen::Dynamic, 4, RowMajor > > rowMajorMatrix( mpdata.data(), nqp, 4 );
    Eigen::MatrixXd                                      colMajorMatrix = rowMajorMatrix;

    Data data;
    data.normals = colMajorMatrix.block( 0, 0, nqp, 3 );

    // The literal tables above store columns in a scheme-dependent order; N21Symmetric, N28 and
    // N37 need their first and third (x and z) columns swapped to obtain (x,y,z), while
    // N21Asymmetric and N61 are already stored as (x,y,z).
    const bool swapXZ = scheme == QuadratureScheme::N21Symmetric || scheme == QuadratureScheme::N28 ||
                        scheme == QuadratureScheme::N37;
    if ( swapXZ )
      data.normals.col( 0 ).swap( data.normals.col( 2 ) );

    data.weights = colMajorMatrix.block( 0, 3, nqp, 1 );
    if ( scheme != QuadratureScheme::N21Asymmetric )
      data.weights *= 6.;

    return data;
  }

