  /**
   * @class Marmot::Discretizations::Elements::BeamFiberSection
   * @brief The integration of a beam cross section over given section points ("fibers"), independent of the shape of
   * the section and of the beam kinematics.
   *
   * @tparam nDim number of spatial dimensions of the beam, 2 or 3
   *
   * The section knows only its points \f$(y_f, z_f, A_f)\f$ (2D: \f$(y_f, A_f)\f$) in the section coordinates of the
   * beam axis, generated by the user or the framework for any shape (EdelweissFE: rectangles, circles, tubes,
   * I-profiles, polygons with holes, explicit point lists). It maps the generalized strains \f$\boldsymbol{e}\f$ (2D:
   * \f$[ \varepsilon_0, \kappa ]\f$, 3D: \f$[ \varepsilon_0, \kappa_y, \kappa_z, \chi ]\f$) to the section forces
   * \f$\boldsymbol{s}\f$ (2D: \f$[ N, M ]\f$, 3D: \f$[ N, M_y, M_z, T ]\f$, work conjugate) and the section tangent.
   * Every point has its own material instance, created by name through the hypoelastic material factory, and its own
   * state. A point has the axial strain \f$\varepsilon_{11} = \varepsilon_0 + z_f \kappa_y - y_f \kappa_z\f$; points
   * off the axis' centroid and non-principal axes (\f$\int y z \mathrm{d}A \neq 0\f$) couple naturally. In 2D the
   * material is evaluated by Marmot::Materials::MaterialHypoElastic::computeUniaxialStress.
   *
   * Torsion (3D): Saint-Venant torsion without warping, about the centroid \f$(y_c, z_c)\f$ of the points: the points
   * carry the shear strains \f$\gamma_{12} = - \alpha_T ( z_f - z_c ) \chi\f$, \f$\gamma_{13} = \alpha_T ( y_f - y_c )
   * \chi\f$ (the material in the beam stress state \f$\sigma_{22} = \sigma_{33} = \sigma_{23} = 0\f$, see
   * computeFiberStress3D()), scaled by \f$\alpha_T = \sqrt{J / \sum_f ( (y_f-y_c)^2 + (z_f-z_c)^2 ) A_f}\f$
   * such that the elastic torsional stiffness is \f$G J\f$ with the given torsion constant \f$J\f$ (exact for circles
   * and tubes, where \f$\alpha_T = 1\f$). The shear center offset and warping are neglected; plastic torsion is
   * approximate.
   *
   * Kinematics (small or co-rotated strains) are the business of the beam element: a co-rotational element can use
   * the same section with the generalized strains of its co-rotated frame.
   *
   * State of a point: \f$[ \sigma_{11}, \sigma_{12}, \sigma_{13}, \psi, d, \text{material state} ]\f$.
   */
  template < int nDim >
  class BeamFiberSection {

    static_assert( nDim == 2 || nDim == 3, "BeamFiberSection: nDim must be 2 or 3" );

  public:
    static constexpr int nGeneralized    = nDim == 2 ? 2 : 4;
    static constexpr int nFiberStateVars = 5; ///< fiber stress (3), energy and dissipation density
    /// @brief The beam stress state of a 3D fiber, prescribed components: \f$\varepsilon_{11}, \gamma_{12},
    /// \gamma_{13}\f$ (Voigt indices, in the order of the stored fiber stress).
    static constexpr std::array< int, 3 > beamStressPrescribed = { 0, 3, 4 };
    /// @brief The beam stress state of a 3D fiber, stress-free components: \f$\sigma_{22} = \sigma_{33} =
    /// \sigma_{23} = 0\f$.
    static constexpr std::array< int, 3 > beamStressFree = { 1, 2, 5 };

    using VectorGen = Eigen::Matrix< double, nGeneralized, 1 >;
    using MatrixGen = Eigen::Matrix< double, nGeneralized, nGeneralized >;
    using FiberS    = Eigen::Matrix< double, 3, nGeneralized >; ///< generalized strains -> fiber strains

    /// A section point (fiber)
    struct Fiber {
      double y;                           ///< local y coordinate
      double z;                           ///< local z coordinate (0 in 2D)
      double area;                        ///< area (weight)
      FiberS dFiberStrain_dSectionStrain; ///< section strains -> fiber strains [eps11, gamma12, gamma13]
      std::unique_ptr< Marmot::Materials::MaterialHypoElastic > material; ///< the fiber's own material instance
    };

    /// The section points
    std::vector< Fiber > fibers;
    /// The torsion scaling \f$\alpha_T = \sqrt{J / I_p}\f$ (polar moment \f$I_p\f$ of the points about their centroid):
    /// the torsional stiffness is \f$GJ\f$ for the given torsion constant \f$J\f$ (1 for circles and tubes)
    double torsionScaling = 0.0;

    /**
     * Set the section points.
     * @param points 2D: [y_1, A_1, y_2, A_2, ...]; 3D: [y_1, z_1, A_1, ...]
     * @param nPoints the number of points
     * @param J the torsion constant (3D only)
     */
    void setFibers( const double* points, int nPoints, double J = 0.0 )
    {
      constexpr int stride = nDim == 2 ? 2 : 3;
      if ( nPoints < 1 )
        throw std::invalid_argument( Marmot::Utilities::MakeString()
                                     << __PRETTY_FUNCTION__ << ": a section needs points" );
      fibers.clear();
      double area = 0, yc = 0, zc = 0;
      for ( int i = 0; i < nPoints; i++ ) {
        const double* p = points + i * stride;
        Fiber         f{ p[0], nDim == 2 ? 0.0 : p[1], p[stride - 1], FiberS::Zero(), nullptr };
        if ( f.area <= 0 )
          throw std::invalid_argument( Marmot::Utilities::MakeString()
                                       << __PRETTY_FUNCTION__ << ": section point " << i << " has no positive area" );
        area += f.area;
        yc += f.y * f.area;
        zc += f.z * f.area;
        fibers.push_back( std::move( f ) );
      }
      yc /= area;
      zc /= area;

      double polar = 0;
      for ( const auto& f : fibers )
        polar += ( ( f.y - yc ) * ( f.y - yc ) + ( f.z - zc ) * ( f.z - zc ) ) * f.area;
      if constexpr ( nDim == 3 ) {
        if ( J <= 0 || polar <= 0 )
          throw std::invalid_argument( Marmot::Utilities::MakeString()
                                       << __PRETTY_FUNCTION__
                                       << ": a 3D section needs a positive torsion constant and points "
                                          "spread over the section" );
        torsionScaling = std::sqrt( J / polar );
      }
      else
        torsionScaling = 0.0;

      for ( auto& f : fibers ) {
        if constexpr ( nDim == 2 )
          f.dFiberStrain_dSectionStrain << 1, -f.y, //
            0, 0,                                   //
            0, 0;
        else
          f.dFiberStrain_dSectionStrain << 1, f.z, -f.y, 0, //
            0, 0, 0, -torsionScaling * ( f.z - zc ),        //
            0, 0, 0, torsionScaling * ( f.y - yc );
      }
    }

    /// the section constants of the points: A, the first moments int y dA, int z dA, Iy = int z^2 dA, Iz = int y^2
    /// dA, Iyz = int y z dA (w.r.t. the beam axis)
    std::array< double, 6 > integrals() const
    {
      std::array< double, 6 > c{};
      for ( const auto& f : fibers ) {
        c[0] += f.area;
        c[1] += f.y * f.area;
        c[2] += f.z * f.area;
        c[3] += f.z * f.z * f.area;
        c[4] += f.y * f.y * f.area;
        c[5] += f.y * f.z * f.area;
      }
      return c;
    }

    /**
     * @brief Create one material instance per fiber, by name through the factory.
     * @param[in] name        Name of the hypoelastic material.
     * @param[in] properties  Material properties.
     * @param[in] nProperties Number of material properties.
     * @param[in] elLabel     Label of the element, passed to the materials as their number.
     */
    void createMaterials( const std::string& name, const double* properties, int nProperties, int elLabel )
    {
      for ( auto& f : fibers )
        f.material = std::unique_ptr< Marmot::Materials::MaterialHypoElastic >(
          Marmot::Registry::MaterialHypoElasticFactory::createMaterial( name, properties, nProperties, elLabel ) );
    }

    /**
     * @brief Set the characteristic element length of the fiber materials (regularisation of softening materials).
     * @param[in] characteristicLength The length of the part of the element the section represents.
     */
    void setCharacteristicLength( double characteristicLength )
    {
      for ( auto& f : fibers )
        f.material->setCharacteristicElementLength( characteristicLength );
    }

    /// Whether the materials are assigned (all fibers get theirs at once).
    bool hasMaterials() const { return !fibers.empty() && fibers[0].material; }

    /// Number of state variables of one fiber material (0 before the materials are assigned).
    int nMaterialStateVars() const { return hasMaterials() ? fibers[0].material->getNumberOfRequiredStateVars() : 0; }

    /// Number of state variables per fiber (own states + material states).
    int nFiberStride() const { return nFiberStateVars + nMaterialStateVars(); }

    /// Number of state variables of the whole section.
    int getNumberOfRequiredStateVars() const { return static_cast< int >( fibers.size() ) * nFiberStride(); }

    /// Pointer to the states of fiber k within the section states.
    double* fiberState( double* sectionState, size_t k ) const { return sectionState + k * nFiberStride(); }

    /// Zero the fiber states and initialize the material states of every fiber.
    void initializeStateVars( double* sectionState ) const
    {
      for ( size_t k = 0; k < fibers.size(); k++ ) {
        double* fs = fiberState( sectionState, k );
        std::fill( fs, fs + nFiberStateVars, 0.0 );
        fibers[k].material->initializeYourself( fs + nFiberStateVars, nMaterialStateVars() );
      }
    }

    /**
     * Section forces and tangent for the increment of the generalized strains; updates the fiber states.
     * @param[in,out] sectionState the states of all fibers of the section (see fiberState)
     * @param[out]    sectionForces the section forces (the work conjugates of the section strains)
     * @param[out]    dSectionForces_dSectionStrains the section tangent
     * @param[out]    energy       the elastic energy of the section per length
     * @param[out]    dissipation  the dissipation of the section per length
     * @param[in]     dSectionStrain the increment of the section strains
     * @param[in]     time         the current (pseudo-)time
     * @param[in]     dT           the (pseudo-)time increment
     */
    void computeSection( double*          sectionState,
                         VectorGen&       sectionForces,
                         MatrixGen&       dSectionForces_dSectionStrains,
                         double&          energy,
                         double&          dissipation,
                         const VectorGen& dSectionStrain,
                         double           time,
                         double           dT ) const
    {
      sectionForces.setZero();
      dSectionForces_dSectionStrains.setZero();
      energy = dissipation = 0;
      for ( size_t k = 0; k < fibers.size(); k++ ) {
        const Fiber&          fiber           = fibers[k];
        double*               fs              = fiberState( sectionState, k );
        Eigen::Matrix3d       dStress_dStrain = Eigen::Matrix3d::Zero();
        const Eigen::Vector3d dEps            = fiber.dFiberStrain_dSectionStrain * dSectionStrain;

        if constexpr ( nDim == 2 ) {
          Marmot::Materials::MaterialHypoElastic::state1D state;
          state.stress               = fs[0];
          state.elasticEnergyDensity = fs[3];
          state.dissipation          = fs[4];
          state.stateVars            = fs + nFiberStateVars;
          fiber.material->computeUniaxialStress( state, dStress_dStrain( 0, 0 ), dEps( 0 ), { time, dT } );
          fs[0] = state.stress;
          fs[3] = state.elasticEnergyDensity;
          fs[4] = state.dissipation;
        }
        else {
          dStress_dStrain = computeFiberStress3D( *fiber.material, fs, dEps, { time, dT } );
        }

        const Eigen::Map< const Eigen::Vector3d > sigma( fs );
        const auto&                               S = fiber.dFiberStrain_dSectionStrain;
        sectionForces += S.transpose() * sigma * fiber.area;
        dSectionForces_dSectionStrains += S.transpose() * dStress_dStrain * S * fiber.area;
        energy += fs[3] * fiber.area;
        dissipation += fs[4] * fiber.area;
      }
    }

    /**
     * @brief The beam stress state of a 3D fiber: Marmot::ContinuumMechanics::ReducedStress::computeReducedStress()
     * with the prescribed strains beamStressPrescribed and the stress-free components beamStressFree around the 3D
     * stress update of the fiber's material, each evaluation from the start of the increment.
     * @param[in]     material     the fiber's material
     * @param[in,out] fs           the fiber state \f$[ \sigma_{11}, \sigma_{12}, \sigma_{13}, \psi, d, \text{material
     * state} ]\f$ (see BeamFiberSection): in at the start, out at the end of the
     * increment; the material state variables are reset to the start of the increment if the iteration fails
     * @param[in]     dEps         the increment \f$[ \Delta\varepsilon_{11}, \Delta\gamma_{12}, \Delta\gamma_{13} ]\f$
     * @param[in]     timeInfo     the (pseudo-)time and its increment
     * @return the condensed tangent \f$\partial [ \sigma_{11}, \sigma_{12}, \sigma_{13} ] / \partial [
     * \varepsilon_{11}, \gamma_{12}, \gamma_{13} ]\f$
     * @throws Marmot::Utilities::StressUpdateFailed if the iteration fails (cutback)
     */
    static Eigen::Matrix3d computeFiberStress3D( const Marmot::Materials::MaterialHypoElastic&           material,
                                                 double*                                                 fs,
                                                 const Eigen::Vector3d&                                  dEps,
                                                 const Marmot::Materials::MaterialHypoElastic::timeInfo& timeInfo )
    {
      using Marmot::Math::Matrix6d;
      using Marmot::Math::Vector6d;
      constexpr auto& p = beamStressPrescribed;
      constexpr auto& f = beamStressFree;

      // the start of the increment; the free stresses vanish
      Eigen::Map< Eigen::VectorXd > stateVars( fs + nFiberStateVars, material.getNumberOfRequiredStateVars() );
      const Eigen::VectorXd         stateVarsOld = stateVars;
      Vector6d                      stressOld    = Vector6d::Zero();
      for ( int i = 0; i < 3; i++ )
        stressOld( p[i] ) = fs[i];

      Marmot::Materials::MaterialHypoElastic::state3D state;
      state.stateVars = stateVars.data();

      auto computeStress3D = [&]( const Vector6d& dStrain, Vector6d& stress, Matrix6d& dStress_dStrain ) {
        stateVars                  = stateVarsOld;
        state.stress               = stressOld;
        state.elasticEnergyDensity = fs[3];
        state.dissipation          = fs[4];
        material.computeStress( state, dStress_dStrain, dStrain, timeInfo );
        stress = state.stress;
      };

      // initial guess: no lateral strains
      Vector6d dStrain = Vector6d::Zero();
      for ( int i = 0; i < 3; i++ )
        dStrain( p[i] ) = dEps( i );

      try {
        const auto condensation = Marmot::ContinuumMechanics::ReducedStress::computeReducedStress( computeStress3D,
                                                                                                   dStrain,
                                                                                                   p,
                                                                                                   f );
        for ( int i = 0; i < 3; i++ )
          fs[i] = state.stress( p[i] );
        fs[3] = state.elasticEnergyDensity;
        fs[4] = state.dissipation;
        return condensation.dStressP_dStrainP;
      }
      catch ( const Marmot::Utilities::StressUpdateFailed& ) {
        stateVars = stateVarsOld;
        throw;
      }
    }

    /// the state "stress" ([sigma11, sigma12, sigma13]) or a material state of fiber k
    Marmot::Utilities::StateView getFiberStateView( double* sectionState, size_t k, const std::string& name ) const
    {
      if ( k >= fibers.size() )
        throw std::invalid_argument( Marmot::Utilities::MakeString()
                                     << __PRETTY_FUNCTION__ << ": fiber " << k << " does not exist" );
      double* fs = fiberState( sectionState, k );
      if ( name == "stress" )
        return { fs, 3 };
      return fibers[k].material->getStateView( name, fs + nFiberStateVars );
    }
  };

